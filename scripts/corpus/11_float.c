/* float arithmetic + conversions (exercises long combos / support routines) */
float fadd(float a, float b) { return a + b; }
float fsub(float a, float b) { return a - b; }
float fmul(float a, float b) { return a * b; }
float fdiv(float a, float b) { return a / b; }
int f2i(float a) { return (int)a; }
float i2f(int a) { return (float)a; }
long f2l(float a) { return (long)a; }
float l2f(long a) { return (float)a; }
int fcmp(float a, float b) { return a < b; }
